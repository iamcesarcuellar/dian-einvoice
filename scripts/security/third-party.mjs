// docs/third-party-licenses.md from the lists of licenses.mjs --json (scripts/licenses.sh): every production
// dependency of the five applications with its license, how many of each license each application has,
// and the files of third parties kept in the repository, from third-party-files.json (which notices.mjs checks). It
// fails, writing nothing, when a license is not compatible with the MIT License of this project (compatibility.mjs).
// Usage: node third-party.mjs <directory with backend.json, web-app.json, simulator.json, cdk-app.json, functions.json>
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { chosen, compatible, KINDS } from './compatibility.mjs'

const [directory = '/licenses'] = process.argv.slice(2)
const inventory = JSON.parse(readFileSync(new URL('./third-party-files.json', import.meta.url), 'utf8'))

const APPLICATIONS = [
  ['backend', 'Backend', 'backend/composer.lock', 'composer licenses --no-dev', 'the PHP packages of the API, the workers, the relay and the functions'],
  ['web-app', 'Web app', 'frontend/pnpm-lock.yaml', 'pnpm licenses list --prod', 'bundled into the files the browser loads'],
  ['simulator', 'DIAN simulator', 'simulator/package-lock.json', 'npm ls --omit=dev', 'the local stand-in for the DIAN'],
  ['cdk-app', 'CDK app', 'infra/cdk/package-lock.json', 'npm ls --omit=dev', 'the infrastructure as code of the stacks'],
  ['functions', 'Serverless service', 'infra/functions/package-lock.json', 'npm ls --omit=dev', 'the functions in TypeScript, their deployment and the scripts of the emulated cloud'],
]

const lists = APPLICATIONS.map(([key]) => JSON.parse(readFileSync(join(directory, `${key}.json`), 'utf8')))
const refused = lists.flatMap((list) => list.packages.flatMap((item) => item.licenses.filter((license) => !compatible(license)).map((license) => `${list.application}: ${item.name}: ${license || 'no license'}`)))

if (refused.length > 0) {
  console.error(`Licenses missing or not compatible with this project's MIT License:\n  ${refused.join('\n  ')}`)
  process.exit(1)
}

const kindOf = (expression) => [...new Set((chosen(expression) ?? []).map((license) => KINDS.get(license)))].join(', ')
const licenses = [...new Set(lists.flatMap((list) => list.packages.flatMap((item) => item.licenses)))].sort((a, b) => a.localeCompare(b))
const total = lists.reduce((sum, list) => sum + list.packages.length, 0)
// The packages whose installed versions declare different licenses: they count under each.
const several = lists.flatMap((list, index) => list.packages.filter((item) => item.licenses.length > 1).map((item) => `${item.name} (${APPLICATIONS[index][1]}: ${item.licenses.join(', ')})`))
const lines = []

lines.push(
  '# Third-party licenses',
  '',
  '<!-- Generated by make licenses (scripts/licenses.sh, scripts/security/third-party.mjs). Do not edit: make security fails when this file is not what the lock files give. -->',
  '',
  `The production dependencies of this repository's five applications, as their lock files install them: ${total} packages, each with the license it declares. A package installed in more than one version is listed once, with the license of each version, and the versions themselves are in the lock files. Development tools (linters, test runners, the end-to-end test's browser) are not distributed with the code and are not listed. Neither are the local stack's container images, which run as separate processes. The files of others that live in the repository itself come [after the summary](#files-of-third-parties-in-the-repository), and [NOTICE](../NOTICE) gives their notices.`,
  '',
  'This project is under the [MIT License](../LICENSE). Every license below is compatible with it, which `make security` checks on every run against the list in `scripts/security/compatibility.mjs`:',
  '',
  '- **Permissive** licenses (MIT, ISC, BSD, Apache-2.0 and the like) ask to keep their notice, which each package carries.',
  '- **Weak copyleft** licenses (LGPL, EPL, MPL) cover their library\'s files, used here as published: the library stays under its license, and this project\'s code stays MIT.',
  '- **Font** licenses (OFL-1.1) cover the font itself, not the documents or the pages that use it.',
  '- A package with a choice of licenses (`A OR B`) is used under the first compatible alternative.',
  '',
  '## By license',
  '',
  `| License | Kind | ${APPLICATIONS.map(([, title]) => title).join(' | ')} |`,
  `| --- | --- | ${APPLICATIONS.map(() => '---:').join(' | ')} |`,
)

for (const license of licenses) {
  const counts = lists.map((list) => list.packages.filter((item) => item.licenses.includes(license)).length)
  lines.push(`| ${license} | ${kindOf(license)} | ${counts.map((count) => (count === 0 ? '' : String(count))).join(' | ')} |`)
}

lines.push(`| **Packages** | | ${lists.map((list) => `**${list.packages.length}**`).join(' | ')} |`, '')

if (several.length > 0) {
  lines.push(`${several.length === 1 ? 'One package is' : `${several.length} packages are`} installed in versions that declare different licenses, and ${several.length === 1 ? 'counts' : 'count'} under each: ${several.join('; ')}.`, '')
}

const cell = (text) => text.replaceAll('|', '\\|')
const listedFiles = inventory.groups.reduce((sum, group) => sum + group.files.length, 0)

lines.push(
  '## Files of third parties in the repository',
  '',
  `These files are the work of others, kept in the repository under their own terms. [NOTICE](../NOTICE) gives their notices and says that the MIT License of this project does not cover them. \`make security\` checks this list against the repository (\`scripts/security/notices.mjs\`, from \`scripts/security/third-party-files.json\`): every listed file exists, an unchanged one keeps its SHA-256 and its notice, NOTICE names it, and a file that looks like the work of a third party, by its type or by a copyright or license notice in it, fails the check unless it is listed here or declared the project's own.`,
  '',
  `${inventory.groups.length} groups, ${listedFiles} entries:`,
  '',
  '| Files | Owner | Origin | Terms | Unchanged |',
  '| --- | --- | --- | --- | --- |',
)

for (const group of inventory.groups) {
  const files = group.files.map((entry) => (entry.glob !== undefined ? `\`${entry.glob}\`` : entry.sha256 !== undefined ? `\`${entry.path}\` (SHA-256 \`${entry.sha256.slice(0, 12)}…\`)` : `\`${entry.path}\``)).join('<br>')
  lines.push(`| **${cell(group.name)}**<br>${files} | ${cell(group.owner)} | ${cell(group.origin)} [Source](${group.source}). | ${cell(group.terms)} | ${group.unchanged ? 'Yes' : 'No'} |`)
}

lines.push('', '### Excerpts in files of this project', '')

for (const excerpt of inventory.excerpts) {
  lines.push(`- **${excerpt.name}.** ${excerpt.what} In ${excerpt.where.map((where) => `\`${where}\``).join(', ')}. ${excerpt.terms}`)
}

lines.push('', '### Kept out of the repository', '')

for (const outside of inventory.outside) {
  lines.push(`- **${outside.name}.** ${outside.how}`)
}

for (const removed of inventory.removed) {
  lines.push(`- **\`${removed.path}\`**, removed: ${removed.what} ${removed.why}`)
}

lines.push('')

for (const [index, [, title, lock, command, role]] of APPLICATIONS.entries()) {
  const list = lists[index]
  lines.push(`## ${title}`, '', `${list.packages.length} packages from \`${lock}\` (\`${command}\`): ${role}.`, '', '| Package | License |', '| --- | --- |')

  for (const item of list.packages) {
    lines.push(`| ${item.name} | ${item.licenses.join(', ')} |`)
  }

  lines.push('')
}

process.stdout.write(lines.join('\n'))
