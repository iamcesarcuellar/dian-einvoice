// docs/third-party-licenses.md from the lists of licenses.mjs --json (scripts/licenses.sh): every production
// dependency of the five applications with its version and license, how many of each license each application has,
// and the files of third parties kept in the repository. It fails, writing nothing, when a license is not
// compatible with the MIT License of this project (compatibility.mjs).
// Usage: node third-party.mjs <directory with backend.json, web-app.json, simulator.json, cdk-app.json, functions.json>
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { chosen, compatible, KINDS } from './compatibility.mjs'

const [directory = '/licenses'] = process.argv.slice(2)

const APPLICATIONS = [
  ['backend', 'Backend', 'backend/composer.lock', 'composer licenses --no-dev', 'the PHP packages of the API, the workers, the relay and the functions'],
  ['web-app', 'Web app', 'frontend/pnpm-lock.yaml', 'pnpm licenses list --prod', 'bundled into the files the browser loads'],
  ['simulator', 'DIAN simulator', 'simulator/package-lock.json', 'npm ls --omit=dev', 'the local stand-in for the DIAN'],
  ['cdk-app', 'CDK app', 'infra/cdk/package-lock.json', 'npm ls --omit=dev', 'the infrastructure as code of the stacks'],
  ['functions', 'Serverless service', 'infra/functions/package-lock.json', 'npm ls --omit=dev', 'the functions in TypeScript, their deployment and the scripts of the emulated cloud'],
]

const lists = APPLICATIONS.map(([key]) => JSON.parse(readFileSync(join(directory, `${key}.json`), 'utf8')))
const refused = lists.flatMap((list) => list.packages.filter((item) => !compatible(item.license)).map((item) => `${list.application}: ${item.name} ${item.version}: ${item.license || 'no license'}`))

if (refused.length > 0) {
  console.error(`Licenses not compatible with the MIT License of this project, or missing:\n  ${refused.join('\n  ')}`)
  process.exit(1)
}

const kindOf = (expression) => [...new Set((chosen(expression) ?? []).map((license) => KINDS.get(license)))].join(', ')
const licenses = [...new Set(lists.flatMap((list) => list.packages.map((item) => item.license)))].sort((a, b) => a.localeCompare(b))
const total = lists.reduce((sum, list) => sum + list.packages.length, 0)
const lines = []

lines.push(
  '# Third-party licenses',
  '',
  '<!-- Generated by make licenses (scripts/licenses.sh, scripts/security/third-party.mjs). Do not edit: make security fails when this file is not what the lock files give. -->',
  '',
  `The production dependencies of the five applications of this repository, as their lock files install them: ${total} packages, each with the version and the license it declares. Development tools (linters, test runners, the browser of the end-to-end test) are not distributed with the code and are not listed; neither are the container images of the local stack, which run as separate processes.`,
  '',
  'This project is under the [MIT License](../LICENSE). Every license below is compatible with it, which `make security` checks on every run against the list in `scripts/security/compatibility.mjs`:',
  '',
  '- **Permissive** licenses (MIT, ISC, BSD, Apache-2.0 and the like) ask to keep their notice, which each package carries.',
  '- **Weak copyleft** licenses (LGPL, EPL, MPL) cover the files of their library, used here as published: the library stays under its license and the code of this project stays MIT.',
  '- **Font** licenses (OFL-1.1) cover the font itself, not the documents or the pages that use it.',
  '- A package with a choice of licenses (`A OR B`) is used under the first compatible alternative.',
  '',
  '## By license',
  '',
  `| License | Kind | ${APPLICATIONS.map(([, title]) => title).join(' | ')} |`,
  `| --- | --- | ${APPLICATIONS.map(() => '---:').join(' | ')} |`,
)

for (const license of licenses) {
  const counts = lists.map((list) => list.packages.filter((item) => item.license === license).length)
  lines.push(`| ${license} | ${kindOf(license)} | ${counts.map((count) => (count === 0 ? '' : String(count))).join(' | ')} |`)
}

lines.push(`| **Total** | | ${lists.map((list) => `**${list.packages.length}**`).join(' | ')} |`, '')

lines.push(
  '## Files of third parties in the repository',
  '',
  '- `backend/resources/dian/xsd/`: the XML schemas of the DIAN e-invoicing toolbox v1.9, unchanged: the OASIS Universal Business Language 2.1 schemas (Copyright (c) OASIS Open 2013), with the XML Signature and XAdES schemas they import, and `DIAN_UBL_Structures.xsd` of the DIAN. `backend/resources/dian/examples/invoice-example.xml` is an example of the same toolbox. They keep their own notices and are not covered by the MIT License of this project; `backend/resources/dian/SOURCE.txt` says where each one comes from.',
  '- `backend/resources/fonts/inter/`: Inter 4.1 by The Inter Project Authors, under the SIL Open Font License 1.1 (`LICENSE.txt` next to the fonts), embedded in the PDFs; `SOURCE.txt` says where it comes from.',
  '',
)

for (const [index, [, title, lock, command, role]] of APPLICATIONS.entries()) {
  const list = lists[index]
  lines.push(`## ${title}`, '', `${list.packages.length} packages from \`${lock}\` (\`${command}\`): ${role}.`, '', '| Package | Version | License |', '| --- | --- | --- |')

  for (const item of list.packages) {
    lines.push(`| ${item.name} | ${item.version} | ${item.license} |`)
  }

  lines.push('')
}

process.stdout.write(lines.join('\n'))
