<?php

namespace App\Modules\Dian\Http\Resources;

use App\Modules\Dian\Models\SigningCertificate;
use Illuminate\Http\Request;
use Illuminate\Http\Resources\Json\JsonResource;

/**
 * Public metadata of the signing certificate. The private key and the password never leave.
 *
 * @mixin SigningCertificate
 */
final class SigningCertificateResource extends JsonResource
{
    /**
     * @return array<string, mixed>
     */
    public function toArray(Request $request): array
    {
        return [
            'id' => $this->id,
            'subject' => $this->subject,
            'issuer' => $this->issuer,
            'serial_number' => $this->serial_number,
            'fingerprint_sha256' => $this->fingerprint_sha256,
            'valid_from' => $this->valid_from,
            'valid_to' => $this->valid_to,
            // valid, expiring_soon (less than 30 days left), expired or not_yet_valid.
            'status' => $this->status(),
            // A synthetic self-signed certificate generated by this app, not by an accredited authority.
            'is_test' => $this->is_test,
            'created_at' => $this->created_at,
        ];
    }
}
