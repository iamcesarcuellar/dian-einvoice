// Security: the KMS key that protects the signing certificates of the companies (each certificate is
// encrypted with a data key of its own, which only this key can decrypt), and the secret of the
// application in Secrets Manager (APP_KEY, generated here, and the settings of the stage).
import { Stack, type StackProps, Validations } from 'aws-cdk-lib'
import { ManagedPolicy, PolicyStatement } from 'aws-cdk-lib/aws-iam'
import { Key, KeySpec, KeyUsage } from 'aws-cdk-lib/aws-kms'
import { Secret } from 'aws-cdk-lib/aws-secretsmanager'
import type { Construct } from 'constructs'
import { Published } from './published.ts'
import { PROJECT, removalPolicy, resourceName, type StageConfig } from './stage.ts'

export interface SecurityStackProps extends StackProps {
  readonly stage: StageConfig
}

/** The encryption context of every data key of the key store (App\Support\Keys\KmsKeyStore). */
export const SIGNING_KEY_CONTEXT = { purpose: 'signing-certificate', keys: ['company_id', 'entry_id', 'purpose'] } as const

export class SecurityStack extends Stack {
  readonly signingKey: Key
  readonly appSecret: Secret

  constructor(scope: Construct, id: string, props: SecurityStackProps) {
    super(scope, id, props)
    const { stage } = props
    const published = new Published(this, stage, 'security')

    this.signingKey = new Key(this, 'SigningKey', {
      alias: `alias/${resourceName(stage, 'signing-keys')}`,
      description: `Protects the data keys of the signing certificates of dian-einvoice (${stage.name})`,
      keySpec: KeySpec.SYMMETRIC_DEFAULT,
      keyUsage: KeyUsage.ENCRYPT_DECRYPT,
      enableKeyRotation: true,
      removalPolicy: removalPolicy(stage),
    })

    // APP_KEY is generated by Secrets Manager: 32 characters for AES-256-CBC, never in a template.
    this.appSecret = new Secret(this, 'AppSecret', {
      secretName: `${PROJECT}/${stage.name}/app`,
      description: `Secrets of the application dian-einvoice (${stage.name}), read at boot (App\\Support\\Secrets\\LoadSecrets)`,
      generateSecretString: {
        secretStringTemplate: JSON.stringify(stage.secretSettings),
        generateStringKey: 'APP_KEY',
        passwordLength: 32,
        excludePunctuation: true,
      },
      removalPolicy: removalPolicy(stage),
    })

    Validations.of(this.appSecret).acknowledge({
      id: 'AwsSolutions::AwsSolutions-SMG4',
      reason: 'APP_KEY encrypts stored values (PINs, technical keys, webhook secrets): rotating it needs a rotation function that re-encrypts them, which belongs to the compute of Infrastructure task 2 (docs/limitations.md).',
    })

    // The key store only: a data key per certificate, with the encryption context the application
    // always sends, and the decryption of those data keys.
    const useSigningKey = new ManagedPolicy(this, 'UseSigningKeyPolicy', {
      managedPolicyName: resourceName(stage, 'use-signing-key'),
      description: `Create and decrypt the data keys of the signing certificates of dian-einvoice (${stage.name})`,
      statements: [new PolicyStatement({
        actions: ['kms:GenerateDataKey', 'kms:Decrypt'],
        resources: [this.signingKey.keyArn],
        conditions: {
          'StringEquals': { 'kms:EncryptionContext:purpose': SIGNING_KEY_CONTEXT.purpose },
          'ForAllValues:StringEquals': { 'kms:EncryptionContextKeys': [...SIGNING_KEY_CONTEXT.keys] },
        },
      })],
    })

    const readSecret = new ManagedPolicy(this, 'ReadAppSecretPolicy', {
      managedPolicyName: resourceName(stage, 'read-app-secret'),
      description: `Read the secrets of the application dian-einvoice (${stage.name})`,
      statements: [new PolicyStatement({ actions: ['secretsmanager:GetSecretValue', 'secretsmanager:DescribeSecret'], resources: [this.appSecret.secretArn] })],
    })

    published.add('SigningKeyArn', 'signing-key-arn', this.signingKey.keyArn, 'ARN of the KMS key of the signing certificates')
    published.add('SigningKeyAlias', 'signing-key-alias', `alias/${resourceName(stage, 'signing-keys')}`, 'Alias of the KMS key of the signing certificates')
    published.add('AppSecretArn', 'app-secret-arn', this.appSecret.secretArn, 'ARN of the secret of the application')
    published.add('UseSigningKeyPolicyArn', 'policies/use-signing-key', useSigningKey.managedPolicyArn, 'Managed policy for the key store of the application')
    published.add('ReadAppSecretPolicyArn', 'policies/read-app-secret', readSecret.managedPolicyArn, 'Managed policy for the processes that read the secrets of the application')
  }
}
